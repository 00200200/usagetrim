def source_diff(old, new, path):
    import difflib

    return f"diff --git a/{path} b/{path}\nindex 1234567..89abcdef 100644\n" + "".join(
        difflib.unified_diff(
            old.splitlines(keepends=True),
            new.splitlines(keepends=True),
            fromfile=f"a/{path}",
            tofile=f"b/{path}",
        )
    )


